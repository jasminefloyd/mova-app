select has_table('public'::name, 'mova_calendar_sync_settings'::name);
select has_table('public'::name, 'mova_google_oauth_states'::name);
select has_table('public'::name, 'mova_external_calendar_events'::name);
select has_table('public'::name, 'mova_calendar_feed_tokens'::name);
select ok((select relrowsecurity from pg_class where oid='public.mova_google_calendar_connections'::regclass),'Google credentials table has RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.mova_google_oauth_states'::regclass),'OAuth state table has RLS enabled');
