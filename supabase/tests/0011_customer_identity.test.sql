begin;
select plan(18);
select has_table('public'::name, 'mova_customer_accounts'::name);
select has_table('public'::name, 'mova_customer_contact_methods'::name);
select has_table('public'::name, 'mova_client_customer_links'::name);
select has_table('public'::name, 'mova_client_link_suggestions'::name);
select has_column('public'::name, 'mova_appointments'::name, 'customer_account_id'::name, 'customer account link column exists');
select has_column('public'::name, 'mova_appointments'::name, 'client_email_normalized'::name, 'normalized client email column exists');
select has_column('public'::name, 'mova_appointments'::name, 'client_phone_normalized'::name, 'normalized client phone column exists');
select has_function('public'::name, 'mova_link_signed_in_booking'::name, array['uuid','uuid','bytea']::name[]);
select has_trigger('public'::name, 'mova_appointments'::name, 'mova_appointments_normalize_contacts'::name);
select ok((select relrowsecurity from pg_class where oid='public.mova_customer_accounts'::regclass),'customer accounts have RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.mova_customer_contact_methods'::regclass),'verified contact methods have RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.mova_client_customer_links'::regclass),'cross-tenant links have RLS enabled');
select ok((select relrowsecurity from pg_class where oid='public.mova_client_link_suggestions'::regclass),'duplicate suggestions have RLS enabled');
select ok(not has_table_privilege('authenticated','public.mova_customer_accounts','SELECT'),'client account data is API-only');
select ok(not has_table_privilege('authenticated','public.mova_customer_contact_methods','SELECT'),'contact methods are API-only');
select ok(not has_table_privilege('authenticated','public.mova_client_customer_links','SELECT'),'cross-tenant links are API-only');
